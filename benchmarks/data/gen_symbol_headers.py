#!/usr/bin/env python3
"""Generate C++ headers (and gperf inputs) for the ticker benchmarks.

Inputs (checked in, downloaded 2026-08-29):
  nasdaqlisted.txt        https://www.nasdaqtrader.com/dynamic/SymDir/nasdaqlisted.txt
  otherlisted.txt         https://www.nasdaqtrader.com/dynamic/SymDir/otherlisted.txt
  sp500_constituents.csv  https://raw.githubusercontent.com/datasets/s-and-p-500-companies/main/data/constituents.csv

Outputs (next to this script):
  nasdaq_symbols.inc   every non-test Nasdaq-listed symbol (hits) + NYSE/other-listed symbols
                       not on Nasdaq (misses)
  sp500_symbols.inc    every S&P 500 constituent (hits) + Nasdaq-listed symbols not in the
                       S&P 500 (misses)
  nasdaq.gperf / sp500.gperf   inputs for GNU gperf (the classic comparison lane)

Symbols are sorted and de-duplicated so the key order is reproducible.
"""
import csv, os, random

here = os.path.dirname(os.path.abspath(__file__))

def read_nasdaq_trader(path, sym_col=0, test_col=None):
    out = []
    with open(os.path.join(here, path), encoding="utf-8") as f:
        header = f.readline().rstrip("\n").split("|")
        for line in f:
            if line.startswith("File Creation Time"): continue
            cols = line.rstrip("\n").split("|")
            if len(cols) < 2: continue
            sym = cols[sym_col].strip()
            if not sym: continue
            if test_col is not None and cols[test_col].strip() == "Y": continue
            out.append(sym)
    return header, out

hdr, nasdaq = read_nasdaq_trader("nasdaqlisted.txt", sym_col=0, test_col=3)   # Test Issue column
hdr2, other = read_nasdaq_trader("otherlisted.txt", sym_col=0, test_col=6)     # Test Issue column
# otherlisted.txt "ACT Symbol" may contain $ / = for preferreds/warrants; keep plain [A-Z.-] symbols
import re
plain = re.compile(r"^[A-Z][A-Z.\-]{0,7}$")
nasdaq = sorted({s for s in nasdaq if plain.match(s)})
other  = sorted({s for s in other  if plain.match(s)})

sp500 = []
with open(os.path.join(here, "sp500_constituents.csv"), encoding="utf-8") as f:
    for row in csv.DictReader(f):
        s = row["Symbol"].strip()
        if plain.match(s): sp500.append(s)
sp500 = sorted(set(sp500))

nasdaq_set, sp500_set = set(nasdaq), set(sp500)
nasdaq_misses = [s for s in other if s not in nasdaq_set]
sp500_misses  = [s for s in nasdaq if s not in sp500_set]
rng = random.Random(20260829)
rng.shuffle(nasdaq_misses); rng.shuffle(sp500_misses)
nasdaq_misses = sorted(nasdaq_misses[:len(nasdaq)])   # same size as the hit set
sp500_misses  = sorted(sp500_misses[:len(sp500)])

def emit_inc(fname, hits_name, hits, miss_name, misses, comment):
    with open(os.path.join(here, fname), "w", encoding="utf-8") as f:
        f.write(f"// GENERATED by gen_symbol_headers.py — do not edit.\n// {comment}\n")
        f.write("#pragma once\n#include <array>\n#include <string_view>\n\n")
        for name, syms in ((hits_name, hits), (miss_name, misses)):
            f.write(f"inline constexpr std::array<std::string_view, {len(syms)}> {name} = {{\n")
            for i in range(0, len(syms), 12):
                f.write("    " + ",".join(f'"{s}"' for s in syms[i:i+12]) + ",\n")
            f.write("};\n\n")
        mx = max(len(s) for s in hits)
        f.write(f"inline constexpr std::size_t {hits_name}_max_len = {mx};\n")

emit_inc("nasdaq_symbols.inc", "nasdaq_symbols", nasdaq, "nasdaq_miss_symbols", nasdaq_misses,
         f"{len(nasdaq)} Nasdaq-listed symbols (non-test issues), misses = other-listed symbols not on Nasdaq")
emit_inc("sp500_symbols.inc", "sp500_symbols", sp500, "sp500_miss_symbols", sp500_misses,
         f"{len(sp500)} S&P 500 constituents, misses = Nasdaq-listed symbols not in the index")

def emit_gperf(fname, cls, syms):
    with open(os.path.join(here, fname), "w", encoding="utf-8") as f:
        f.write(f"%{{\n#include <string.h>\n%}}\n%language=C++\n%define class-name {cls}\n")
        f.write("%define lookup-function-name lookup\n%readonly-tables\n%compare-strncmp\n%%\n")
        for s in syms: f.write(s + "\n")
        f.write("%%\n")

emit_gperf("nasdaq.gperf", "NasdaqGperf", nasdaq)
emit_gperf("sp500.gperf", "Sp500Gperf", sp500)

from collections import Counter
for name, syms in (("nasdaq", nasdaq), ("sp500", sp500)):
    lens = Counter(len(s) for s in syms)
    print(f"{name}: {len(syms)} symbols, lengths {dict(sorted(lens.items()))}, "
          f"charset {''.join(sorted(set(''.join(syms))))}")
print(f"nasdaq misses {len(nasdaq_misses)}, sp500 misses {len(sp500_misses)}")
